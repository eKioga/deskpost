<#
.SYNOPSIS
    The single manifest-generation transaction: one Book's manifest is generated, stored, and
    committed under that Book's own lock. Dot-sourced; never invoked directly.

.DESCRIPTION
    Plan item 2.2, third rung. The second rung made the ORDER safe -- dirty marker, generation,
    commit pointer last, marker cleared last of all -- so that every crash leaves a state the read
    path can classify. Ordering survives a crash. It does not survive a second writer.

    THIS RUNG MAKES CONCURRENT WRITERS IMPOSSIBLE RATHER THAN MERELY UNLIKELY. The lock is 0.7's
    per-Book lock, the same one every Shelf writer already takes -- not a second lock beside it, as
    PLAN.md 0.7 requires: "Phase 2.2's manifest generations extend this same lock to cover
    dirty-marker creation and commit-pointer publication; they do not introduce a second one." It is
    held from BEFORE the dirty marker is set until AFTER the commit pointer is written, and it wraps
    Save-BookManifest and nothing else.

    A CALLER THAT ALREADY HOLDS THE LOCK PASSES IT IN. Enter-BookLock is not re-entrant -- it wins a
    CreateNew race, so a second acquisition by the same process blocks against itself and then
    throws. Rung 4 retrofits mutators that hold the Book lock across their own mutation, and they
    must extend that same lock over the manifest rather than deadlock against it. -Lock is that
    path: the transaction verifies the handle is for this Book, uses it, and does not release what
    it did not acquire.

    THE MANIFEST IS GENERATED BEFORE THE MARKER IS SET, DELIBERATELY. Generation reads the Book and
    can fail -- an uncatalogued slug is refused outright by rung 1. A failure there must leave no
    dirty marker behind, because a marker with no repair to follow it is a Book that reads
    unavailable forever. Once the marker IS set, a failure leaves it in place on purpose: the Book
    was mutated and its stored manifest is now stale, so refusing until a rebuild is the honest
    state, and it is the bias rung 2 chose -- refusing a good manifest costs a rebuild, serving a
    bad one costs a wrong answer that looks right.

    GENERATION READS BODIES; IT DOES NOT AUTHORIZE READING THEM. Unchanged from rung 1: the caller
    owes the Desk gate, or backfill's explicit closed-content approval, before it gets here.
#>

Set-StrictMode -Version Latest

