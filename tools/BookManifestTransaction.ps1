if ($MyInvocation.InvocationName -ne '.' -and $args -contains '-SelfTest') {
    $script:failures = [Collections.Generic.List[string]]::new()
    $script:checks = 0
    function Assert([bool]$Condition, [string]$Message) {
        $script:checks++
        if (-not $Condition) { [void]$script:failures.Add($Message) }
    }

    $utf8 = [Text.UTF8Encoding]::new($false)
    function Write-Fixture([string]$Path, [string]$Text) {
        $dir = Split-Path -Parent $Path
        if (-not (Test-Path -LiteralPath $dir -PathType Container)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
        [IO.File]::WriteAllText($Path, $Text, $utf8)
    }

    $fixture = Join-Path ([IO.Path]::GetTempPath()) ('book-manifest-txn-selftest-' + [Guid]::NewGuid().ToString('n'))
    # An unexpected error inside the body would otherwise unwind straight past the remaining
    # assertions and be reported as a pass over however many had run -- observed on the first run of
    # this very suite, where a strict-mode property error left it announcing one check and success.
    try {
        Write-Fixture (Join-Path $fixture 'shelf/_catalog.md') @'
# Local Shelf

## Demo Book
- **Summary:** A curated demo Book for the manifest transaction.
- **Topics:** demo, curated
- **Path:** shelf/demo

## Inbox
- **Summary:** Captures awaiting review.
- **Topics:** capture
- **Kind:** capture
- **Path:** shelf/inbox
'@

        Write-Fixture (Join-Path $fixture 'shelf/demo/wiki/_book.md') "# Demo Book`n`n- **Type:** fixture`n"
        Write-Fixture (Join-Path $fixture 'shelf/demo/wiki/_index.md') "# Demo Book - Reader Map`n`n- [[_book|Book metadata]]`n- [[topic/plain]]`n"
        Write-Fixture (Join-Path $fixture 'shelf/demo/wiki/topic/plain.md') "# Real Title`n`nBody text.`n`n## A Real Section`n"

        Write-Fixture (Join-Path $fixture 'shelf/inbox/wiki/_book.md') "# Inbox`n`n- **Kind:** capture`n"
        Write-Fixture (Join-Path $fixture 'shelf/inbox/wiki/_index.md') "# Inbox - Reader Map`n`n- [[notes/secret-note|Sekrit Capture Title]]`n"
        Write-Fixture (Join-Path $fixture 'shelf/inbox/wiki/notes/secret-note.md') "---`ncaptured: 2026-08-18T00:00:00Z`nreview: pending`n---`n`n# Sekrit Capture Title`n`nUnvetted body.`n"

        $demoStore = Get-BookManifestStorePath -Workspace $fixture -Slug 'demo'
        $lockDir = Join-Path $fixture 'internal/book-locks'
        function Get-LockFiles {
            if (Test-Path -LiteralPath $lockDir -PathType Container) { @(Get-ChildItem -LiteralPath $lockDir -File -Filter '*.lock') } else { @() }
        }

        # --- A bad slug is refused before any lock exists --------------------------------------------
        $refused = $false
        try { Invoke-BookManifestTransaction -Workspace $fixture -Slug 'Foo' -Reason 'selftest bad slug' | Out-Null }
        catch { $refused = $true }
        Assert $refused 'an invalid slug was accepted by the transaction'
        Assert (@(Get-LockFiles).Count -eq 0) 'a refused slug left a lock file behind'

        # --- The lock is taken BEFORE the dirty marker -----------------------------------------------
        # Held by another writer, the transaction must fail having written nothing at all. Were the
        # marker set first, this Book would now read dirty with no mutation behind it to repair.
        $blocker = Enter-BookLock -Workspace $fixture -BookRoot 'shelf/demo' -TimeoutSeconds 5
        $blocked = $false
        try { Invoke-BookManifestTransaction -Workspace $fixture -Slug 'demo' -Reason 'selftest blocked' -TimeoutSeconds 1 | Out-Null }
        catch { $blocked = $true }
        Assert $blocked 'the transaction ran while another writer held the Book lock'
        Assert (-not (Test-Path -LiteralPath (Join-Path $demoStore 'dirty.json') -PathType Leaf)) 'a blocked transaction set a dirty marker'
        Assert ((Get-StoredBookManifest -Workspace $fixture -Slug 'demo').status -ceq 'missing') 'a blocked transaction left stored state behind'

        # --- A caller that already holds the lock passes it in ---------------------------------------
        $passed = Invoke-BookManifestTransaction -Workspace $fixture -Slug 'demo' -Reason 'selftest caller lock' -Lock $blocker
        Assert ($passed.generation -eq 1) "the first committed generation was $($passed.generation), not 1"
        Assert (-not $passed.lock_acquired) 'the transaction reported acquiring a lock it was handed'
        Assert (Test-Path -LiteralPath $blocker.path -PathType Leaf) 'the transaction released a lock it did not acquire'
        Assert ((Get-StoredBookManifest -Workspace $fixture -Slug 'demo').status -ceq 'ok') 'the manifest committed under a caller lock did not read back ok'
        Exit-BookLock -Lock $blocker

        # --- A lock for a different Book is refused, and nothing is written ---------------------------
        $wrong = Enter-BookLock -Workspace $fixture -BookRoot 'shelf/other' -TimeoutSeconds 5
        $mismatch = $false
        try { Invoke-BookManifestTransaction -Workspace $fixture -Slug 'demo' -Reason 'selftest wrong lock' -Lock $wrong | Out-Null }
        catch { $mismatch = $true }
        Assert $mismatch 'a lock for another Book was accepted as this Book''s lock'
        Assert (-not (Test-Path -LiteralPath (Join-Path $demoStore 'dirty.json') -PathType Leaf)) 'a mismatched lock still set a dirty marker'
        Exit-BookLock -Lock $wrong

        # --- The same Book spelled differently is the same lock ---------------------------------------
        $spelled = Enter-BookLock -Workspace $fixture -BookRoot 'shelf/demo/' -TimeoutSeconds 5
        $viaSpelling = Invoke-BookManifestTransaction -Workspace $fixture -Slug 'demo' -BookRoot 'shelf/demo' -Reason 'selftest lock spelling' -Lock $spelled
        Assert ($viaSpelling.generation -eq 2) 'a lock taken under an equivalent Book root spelling was not accepted'
        Exit-BookLock -Lock $spelled

        # --- Acquiring its own lock, and releasing it ------------------------------------------------
        $own = Invoke-BookManifestTransaction -Workspace $fixture -Slug 'demo' -Reason 'selftest own lock'
        Assert $own.lock_acquired 'the transaction did not report acquiring its own lock'
        Assert (@(Get-LockFiles).Count -eq 0) 'the transaction kept the lock it acquired'
        Assert ($own.generation -eq 3) "the third committed generation was $($own.generation)"

        # --- Determinism survives the transaction -----------------------------------------------------
        $again = Invoke-BookManifestTransaction -Workspace $fixture -Slug 'demo' -Reason 'selftest determinism'
        Assert ($again.manifest_sha256 -ceq $own.manifest_sha256) 'an unchanged Book produced a different manifest hash through the transaction'
        $generated = New-BookManifest -Workspace $fixture -Slug 'demo'
        $read = Get-StoredBookManifest -Workspace $fixture -Slug 'demo'
        Assert (($read.manifest | ConvertTo-Json -Depth 12) -ceq ($generated | ConvertTo-Json -Depth 12)) 'the committed manifest is not the one generation produces'
        Assert ($read.source_digest -ceq $generated.source_digest) 'the committed source_digest does not match the Book'

        # --- A failure AFTER the marker leaves the Book dirty, and still releases the lock -------------
        # Whatever called this has already mutated the Book, so a stale manifest served as fresh is
        # the one outcome worse than a refusal: the marker stays and the read path keeps refusing.
        $failed = $false
        try { Invoke-BookManifestTransaction -Workspace $fixture -Slug 'demo' -Reason 'selftest mid-failure' -Manifest ([pscustomobject]@{ schema = 1 }) | Out-Null }
        catch { $failed = $true }
        Assert $failed 'a malformed manifest was committed without error'
        Assert (Test-Path -LiteralPath (Join-Path $demoStore 'dirty.json') -PathType Leaf) 'a failed transaction cleared the dirty marker'
        Assert ((Get-StoredBookManifest -Workspace $fixture -Slug 'demo').status -ceq 'dirty') 'a failed transaction left the Book readable'
        Assert (@(Get-LockFiles).Count -eq 0) 'a failed transaction kept the lock'
        Remove-Item -LiteralPath (Join-Path $demoStore 'dirty.json') -Force

        # --- A failure BEFORE the marker leaves no marker at all ---------------------------------------
        # An uncatalogued Book is refused by generation. A marker written here would be a Book that
        # reads unavailable forever, with no mutation behind it that a rebuild could repair.
        $uncatalogued = $false
        try { Invoke-BookManifestTransaction -Workspace $fixture -Slug 'nowhere' -Reason 'selftest uncatalogued' | Out-Null }
        catch { $uncatalogued = $true }
        Assert $uncatalogued 'an uncatalogued Book was generated by the transaction'
        Assert (-not (Test-Path -LiteralPath (Join-Path (Get-BookManifestStorePath -Workspace $fixture -Slug 'nowhere') 'dirty.json') -PathType Leaf)) 'a generation failure left a dirty marker behind'
        Assert (@(Get-LockFiles).Count -eq 0) 'a generation failure kept the lock'

        # --- The leak canary, carried through the transaction -------------------------------------------
        $inbox = Invoke-BookManifestTransaction -Workspace $fixture -Slug 'inbox' -Reason 'selftest capture'
        $inboxGen = Join-Path (Get-BookManifestStorePath -Workspace $fixture -Slug 'inbox') "generations/$($inbox.generation).json"
        $inboxText = [IO.File]::ReadAllText($inboxGen)
        Assert ($inboxText -cnotmatch 'Sekrit Capture Title') 'a capture note title reached the committed generation file'
        Assert ($inboxText -cnotmatch 'secret-note') 'a capture note path reached the committed generation file'
        Assert ($inboxText -cnotmatch 'Unvetted body') 'capture note body text reached the committed generation file'

        # --- The mutation window: the marker is down BEFORE the writer touches anything --------------
        # This is the half rung 4 adds. A writer that only committed AFTERWARDS would leave the Book
        # reading `ok` for the whole span between its last write and its commit -- a stale manifest
        # that answers, which is the one outcome the marker exists to prevent.
        $mutLock = Enter-BookLock -Workspace $fixture -BookRoot 'shelf/demo' -TimeoutSeconds 5
        $mutation = Enter-BookMutation -Workspace $fixture -Slug 'demo' -Reason 'selftest window' -Lock $mutLock
        Assert ((Get-StoredBookManifest -Workspace $fixture -Slug 'demo').status -ceq 'dirty') 'an open mutation window still read as available'
        Write-Fixture (Join-Path $fixture 'shelf/demo/wiki/topic/added.md') "# Added Under The Window`n`n## A New Section`n"
        $closed = Complete-BookMutation -Mutation $mutation
        Assert ($closed.status -ceq 'committed') "closing the mutation window reported $($closed.status)"
        $afterWindow = Get-StoredBookManifest -Workspace $fixture -Slug 'demo'
        Assert ($afterWindow.status -ceq 'ok') 'a closed mutation window did not read back ok'
        Assert ($afterWindow.source_digest -ceq (New-BookManifest -Workspace $fixture -Slug 'demo').source_digest) 'the committed manifest does not describe the Book as it now stands'
        Assert (Test-Path -LiteralPath $mutLock.path -PathType Leaf) 'closing a mutation window released the writer''s lock'

        # --- A lock for another Book cannot open a window, and sets no marker ------------------------
        $foreign = Enter-BookLock -Workspace $fixture -BookRoot 'shelf/elsewhere' -TimeoutSeconds 5
        $windowRefused = $false
        try { Enter-BookMutation -Workspace $fixture -Slug 'demo' -Reason 'selftest foreign lock' -Lock $foreign | Out-Null }
        catch { $windowRefused = $true }
        Assert $windowRefused 'a window opened on another Book''s lock'
        Assert ((Get-StoredBookManifest -Workspace $fixture -Slug 'demo').status -ceq 'ok') 'a refused window still marked the Book dirty'
        Exit-BookLock -Lock $foreign

        # --- A verified rollback clears the marker; the previous manifest is true again --------------
        $priorGeneration = $afterWindow.generation
        $rolledBack = Enter-BookMutation -Workspace $fixture -Slug 'demo' -Reason 'selftest rollback' -Lock $mutLock
        Assert ((Get-StoredBookManifest -Workspace $fixture -Slug 'demo').status -ceq 'dirty') 'the rollback window did not mark the Book dirty'
        $undone = Undo-BookMutation -Mutation $rolledBack
        Assert ($undone.status -ceq 'cleared') "undoing a mutation reported $($undone.status)"
        $afterUndo = Get-StoredBookManifest -Workspace $fixture -Slug 'demo'
        Assert ($afterUndo.status -ceq 'ok') 'an undone mutation left the Book unavailable'
        Assert ($afterUndo.generation -eq $priorGeneration) 'an undone mutation moved the committed generation'

        # --- Completing NEVER throws, so a manifest failure cannot undo a landed write ---------------
        # An uncatalogued Book is refused by generation. The writer that got here has already changed
        # the Book, so the honest outcome is a reported refusal and a marker left standing -- never an
        # exception that unwinds into the writer's rollback and discards the reader's material.
        $orphanLock = Enter-BookLock -Workspace $fixture -BookRoot 'shelf/nowhere' -TimeoutSeconds 5
        $orphan = Enter-BookMutation -Workspace $fixture -Slug 'nowhere' -Reason 'selftest uncatalogued window' -Lock $orphanLock
        $orphanResult = Complete-BookMutation -Mutation $orphan
        Assert ($orphanResult.status -ceq 'dirty') 'a failed manifest generation was not reported as dirty'
        Assert ($orphanResult.summary -cmatch 'dirty until rebuilt') 'the dirty status did not say what it costs to repair'
        Assert ((Get-StoredBookManifest -Workspace $fixture -Slug 'nowhere').status -ceq 'dirty') 'a failed completion cleared the marker'
        Exit-BookLock -Lock $orphanLock
        Remove-BookManifestStore -Workspace $fixture -Slug 'nowhere' | Out-Null

        # --- A change of identity retires the old store rather than orphaning it ---------------------
        Write-Fixture (Join-Path $fixture 'shelf/_catalog.md') @'
# Local Shelf

## Demo Book Renamed
- **Summary:** A curated demo Book for the manifest transaction.
- **Topics:** demo, curated
- **Path:** shelf/renamed

## Inbox
- **Summary:** Captures awaiting review.
- **Topics:** capture
- **Kind:** capture
- **Path:** shelf/inbox
'@
        $renameMutation = Enter-BookMutation -Workspace $fixture -Slug 'demo' -Reason 'selftest rename' -Lock $mutLock
        Move-Item -LiteralPath (Join-Path $fixture 'shelf/demo') -Destination (Join-Path $fixture 'shelf/renamed')
        $renamedLock = Enter-BookLock -Workspace $fixture -BookRoot 'shelf/renamed' -TimeoutSeconds 5
        $renameResult = Complete-BookRenameMutation -Mutation $renameMutation -NewSlug 'renamed' -NewLock $renamedLock
        Assert ($renameResult.status -ceq 'committed') "the rename completion reported $($renameResult.status)"
        Assert (-not (Test-Path -LiteralPath $demoStore)) 'the renamed Book left its old store behind as an orphan'
        $afterRename = Get-StoredBookManifest -Workspace $fixture -Slug 'renamed'
        Assert ($afterRename.status -ceq 'ok') 'the renamed Book''s store did not read back ok'
        Assert ($afterRename.manifest.slug -ceq 'renamed') 'the committed manifest still names the old slug'
        Assert ($renameResult.generation -eq 1) "the renamed identity started at generation $($renameResult.generation), not 1"
        Exit-BookLock -Lock $renamedLock
        Exit-BookLock -Lock $mutLock
        Assert (@(Get-LockFiles).Count -eq 0) 'the mutation-window cases left a lock behind'
    }
    catch {
        [void]$script:failures.Add("the suite did not run to completion: $($_.Exception.Message)")
    }
    finally {
        Remove-Item -LiteralPath $fixture -Recurse -Force -ErrorAction SilentlyContinue
    }

    if ($script:failures.Count) {
        [Console]::Error.WriteLine("BookManifestTransaction self-test FAILED: $($script:failures -join '; ')")
        exit 1
    }
    Write-Host "BookManifestTransaction self-test passed ($($script:checks) checks)."
    exit 0
}
