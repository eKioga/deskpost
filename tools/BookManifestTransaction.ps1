. (Join-Path $PSScriptRoot 'BookManifest.ps1')
. (Join-Path $PSScriptRoot 'BookManifestStore.ps1')

# Rung 7. The lock has always distinguished the two collections and the store now does too, so the
# one way left to get them wrong is to pass a `books/` root with a `shelf` store key -- which would
# lock one Book and write another Book's manifest. Cross-checked here rather than inferred, because
# inferring the collection from the root would make a caller's mistake invisible instead of fatal.
#
# THE ARCHIVES MADE `StartsWith` WRONG. This compared the root against a prefix, and
# `shelf/_archive/godot`.StartsWith('shelf/') is TRUE -- so an archived Book passed as `shelf` and
# would have written its manifest into its ACTIVE twin's store, which is the exact collision rung 7
# built the collection key to prevent. The root is now taken apart by the schema and its OWN manifest
# collection compared for equality, which no prefix can satisfy by accident.
function Assert-BookCollectionMatchesRoot([string]$Collection, [string]$BookRoot) {
    if ($Collection -cnotin (Get-BookManifestCollections)) { throw "Book collection '$Collection' must be one of: $((Get-BookManifestCollections) -join ', ')." }
    $actual = $null
    try { $actual = (Split-BookRoot $BookRoot).manifest_collection }
    catch { throw "Book root '$BookRoot' is not a well-formed Book root, so no collection can answer for it." }
    if ($actual -cne $Collection) {
        throw "Book root '$BookRoot' does not belong to the '$Collection' collection; it belongs to '$actual'. A '$Collection' Book's root starts with '$((Split-BookManifestCollection $Collection).root_prefix)/'."
    }
}

function Invoke-BookManifestTransaction {
    <#
    .SYNOPSIS
        Generate, store, and commit one Book's manifest under that Book's lock.

    .PARAMETER Lock
        A lock handle the caller already holds for this Book. When given, the transaction uses it
        and leaves it held; when omitted, the transaction acquires and releases its own.

    .PARAMETER Manifest
        A manifest already generated by the caller. When omitted, one is generated inside the
        transaction, before the dirty marker is set.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)][string]$Workspace,
        [Parameter(Mandatory = $true)][string]$Slug,
        [string]$BookRoot = '',
        [Parameter(Mandatory = $true)][string]$Reason,
        [object]$Manifest = $null,
        [object]$Lock = $null,
        [int]$TimeoutSeconds = 20,
        [string]$Collection = 'shelf'
    )

    if ([string]::IsNullOrWhiteSpace($BookRoot)) { $BookRoot = New-BookRootFromManifestCollection $Collection $Slug }
    Assert-BookCollectionMatchesRoot -Collection $Collection -BookRoot $BookRoot

    # Refused before a lock is taken, so a bad name cannot leave a lock file behind. The store
    # applies the same rule when it builds a path; applying it here too means the refusal happens
    # before any state exists rather than halfway through.
    if ($Slug -cnotmatch '^[a-z0-9][a-z0-9-]*$') {
        throw "Book slug '$Slug' must contain only lowercase letters, digits, and hyphens."
    }

    $ownsLock = $false
    if ($null -ne $Lock) {
        # A handle for the wrong Book is worse than no handle: it would run the whole transaction
        # believing it was protected while another writer held the Book it is actually touching.
        $held = ConvertTo-BookLockName $Lock.book_root
        $wanted = ConvertTo-BookLockName $BookRoot
        if ($held -cne $wanted) {
            throw "The lock handed to this transaction is for '$($Lock.book_root)', not for '$BookRoot'."
        }
    }
    else {
        $Lock = Enter-BookLock -Workspace $Workspace -BookRoot $BookRoot -TimeoutSeconds $TimeoutSeconds
        $ownsLock = $true
    }

    try {
        # Inside the lock, and before the marker: a generation failure must leave nothing behind.
        if ($null -eq $Manifest) {
            # Only the ACTIVE Shelf can be generated from here. A shared Book's pages arrive over MCP
            # and this file has no client and must not grow one; and an ARCHIVED Shelf Book is absent
            # from shelf/_catalog.md by design, so New-BookManifest -- which resolves a slug through
            # that catalog -- would refuse it as uncatalogued. Both cases build the manifest in the
            # caller, which has the pages and the metadata, and hand it in.
            if ($Collection -cne 'shelf') { throw "A '$Collection' Book's manifest must be generated by its caller and passed in; Book '$Slug' arrived without one." }
            $Manifest = New-BookManifest -Workspace $Workspace -Slug $Slug
        }

        $pointer = Save-BookManifest -Workspace $Workspace -Slug $Slug -Manifest $Manifest -Reason $Reason -Collection $Collection

        [pscustomobject]@{
            slug            = $Slug
            book_root       = $BookRoot
            collection      = $Collection
            generation      = $pointer.generation
            manifest_sha256 = $pointer.manifest_sha256
            source_digest   = $pointer.source_digest
            committed_utc   = $pointer.committed_utc
            lock_acquired   = $ownsLock
        }
    }
    catch {
        # Deliberately not cleared. If the marker exists, the mutation that prompted this
        # transaction has already touched the Book, and a refusal is the truthful answer until
        # something rebuilds it.
        throw "The manifest transaction for Book '$Slug' failed and its stored manifest is now marked dirty until rebuilt: $($_.Exception.Message)"
    }
    finally {
        # Only what this transaction acquired. Releasing a caller's lock would end the caller's
        # mutation window in the middle of the caller's mutation.
        if ($ownsLock) { Exit-BookLock -Lock $Lock }
    }
}

# ---------------------------------------------------------------------------------------------------
# The mutation window: what a Shelf writer actually calls.
#
# Rung 4. Invoke-BookManifestTransaction on its own commits a manifest for a Book that was mutated
# some time before -- and "some time before" is the whole problem. Between a writer's last write and
# its call to the transaction there is a window in which the Book has changed and the stored manifest
# still reads `ok`: exactly the silently-stale answer the dirty marker exists to prevent, and PLAN.md
# 2.2 is explicit that the marker goes down BEFORE the mutation, not after it.
#
# So a writer does not call the transaction. It OPENS A MUTATION WINDOW and then closes it:
#
#     $lock     = Enter-BookLock ...
#     $mutation = Enter-BookMutation ... -Lock $lock     # marker down, before the first write
#     ... journal, mutate, verify ...
#     Complete-BookMutation -Mutation $mutation          # generate, store, commit, marker up
#
# and on a failure whose rollback VERIFIED, Undo-BookMutation instead -- the Book is back to the
# state the stored manifest already describes, so the marker must come up or the Book reads
# unavailable forever with nothing left to repair.
#
# COMPLETING NEVER THROWS, AND THAT IS THE POINT. The mutation has already landed and been verified
# by the time it is called. A manifest failure must not roll back the reader's page, note, or rename:
# it leaves the marker down, the Book reads `dirty`, and Discovery refuses to describe it until a
# rebuild. Rung 2's bias, one layer further out -- refusing a good manifest costs a rebuild, serving
# a bad one costs a wrong answer that looks right, and discarding a landed write costs the reader
# their material. It returns a status the writer reports, the way Get-StoredBookManifest does.
# ---------------------------------------------------------------------------------------------------

function Enter-BookMutation {
    <#
    .SYNOPSIS
        Mark a Book dirty before a writer changes it, and hold everything the commit will need.

    .PARAMETER Lock
        Mandatory, and not a convenience: a mutation window without exclusion is a window two
        writers can be inside at once, which is the case rung 3 exists to make impossible. The
        handle must name this Book.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)][string]$Workspace,
        [Parameter(Mandatory = $true)][string]$Slug,
        [string]$BookRoot = '',
        [Parameter(Mandatory = $true)][string]$Reason,
        [Parameter(Mandatory = $true)][object]$Lock,
        [string]$Collection = 'shelf'
    )

    if ([string]::IsNullOrWhiteSpace($BookRoot)) { $BookRoot = New-BookRootFromManifestCollection $Collection $Slug }
    Assert-BookCollectionMatchesRoot -Collection $Collection -BookRoot $BookRoot
    if ($Slug -cnotmatch '^[a-z0-9][a-z0-9-]*$') {
        throw "Book slug '$Slug' must contain only lowercase letters, digits, and hyphens."
    }

    $held = ConvertTo-BookLockName $Lock.book_root
    $wanted = ConvertTo-BookLockName $BookRoot
    if ($held -cne $wanted) {
        throw "The lock handed to this mutation is for '$($Lock.book_root)', not for '$BookRoot'."
    }

    $marker = Set-BookManifestDirty -Workspace $Workspace -Slug $Slug -Reason $Reason -Collection $Collection

    [pscustomobject]@{
        workspace  = $Workspace
        slug       = $Slug
        book_root  = $BookRoot
        collection = $Collection
        reason     = $Reason
        lock       = $Lock
        marker     = $marker
    }
}

function Complete-BookMutation {
    <#
    .SYNOPSIS
        Close a mutation window by committing the manifest that describes the change. Never throws.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)][object]$Mutation,
        # A manifest the caller generated. Mandatory in practice for a shared Book, whose pages this
        # file cannot read; omitted for the Shelf, which generates inside the transaction.
        [object]$Manifest = $null
    )

    try {
        $pointer = Invoke-BookManifestTransaction `
            -Workspace $Mutation.workspace -Slug $Mutation.slug -BookRoot $Mutation.book_root `
            -Reason $Mutation.reason -Lock $Mutation.lock -Collection $Mutation.collection -Manifest $Manifest
        [pscustomobject]@{
            status     = 'committed'
            slug       = $Mutation.slug
            generation = $pointer.generation
            summary    = "generation $($pointer.generation) committed"
        }
    }
    catch {
        [pscustomobject]@{
            status     = 'dirty'
            slug       = $Mutation.slug
            generation = 0
            summary    = "dirty until rebuilt: $($_.Exception.Message)"
        }
    }
}

function New-BookMutationFailure {
    <#
    .SYNOPSIS
        The result a manifest updater reports when the lock or the mutation window failed. One
        function, so a later edit cannot fix one updater and miss the other.

    .DESCRIPTION
        WHY THIS IS A FUNCTION AND NOT TWO CATCH BLOCKS. Until 2026-09-06 both updaters wrapped
        `Enter-BookLock` AND `Enter-BookMutation` in a single try, then labelled ANY throw from it
        `locked by another writer` -- each asserting in a comment that nothing else could throw.
        Enter-BookMutation, inside that try, validates the slug, validates the collection against
        the Book root, validates the lock's identity, and writes the dirty marker: four ways to
        fail, all reported as contention that had not happened. A shared rebuild hit exactly that
        on 2026-09-05 and the journals could not contradict the label, so the cause is still
        unknown rather than diagnosed. The two updaters drifted because the rule lived twice.

    .PARAMETER Stage
        Where it failed, which is what decides the status:
          acquire -- Enter-BookLock did not return. Nothing has been touched, because the marker is
                     written INSIDE the lock, so `skipped` is accurate for every acquire failure --
                     contention, an empty Book root, or a lock directory that could not be created.
                     The message is passed through unchanged: Enter-BookLock's own contention text
                     already names the Book and the lock path.
          open    -- Enter-BookMutation threw. The marker may or may not be down, so the Book's
                     state on disk is unknown. `dirty` is still the outcome to report: it is the
                     status that counts toward dirty_books, exits non-zero, and tells the operator
                     to re-run -- the right action whether the slug is malformed or the marker
                     could not be written. The detail carries what actually happened.
          commit  -- generation or the transaction failed with the marker down. `dirty` and a
                     re-run, which is what Complete-BookMutation reports for itself.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)][string]$Slug,
        [Parameter(Mandatory = $true)][ValidateSet('acquire', 'open', 'commit')][string]$Stage,
        [Parameter(Mandatory = $true)][AllowEmptyString()][string]$Message
    )

    # An empty message is how 'locked by another writer' outlived the truth for a year: a report
    # that carries no cause cannot be checked against what happened. Refuse it at the source.
    if ([string]::IsNullOrWhiteSpace($Message)) {
        throw "A '$Stage' failure must carry the message it failed with; a causeless report is the defect this function exists to prevent."
    }

    $status = if ($Stage -ceq 'acquire') { 'skipped' } else { 'dirty' }
    $summary = switch ($Stage) {
        'acquire' { $Message }
        'open'    { "the mutation window would not open: $Message" }
        'commit'  { "dirty until rebuilt: $Message" }
    }
    [pscustomobject]@{ status = $status; slug = $Slug; generation = 0; summary = $summary }
}

function Undo-BookMutation {
    <#
    .SYNOPSIS
        Close a mutation window whose mutation was rolled back and VERIFIED. Never throws.

    .DESCRIPTION
        Only for a rollback that verified, or for a failure that wrote nothing. The Book is then back
        to the state the committed manifest already describes, so the marker is stale and clearing it
        restores a true answer. After a rollback that FAILED the Book is in an unknown state and the
        marker must stay down -- do not call this there.
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory = $true)][object]$Mutation)

    try {
        $marker = Join-Path (Get-BookManifestStorePath -Workspace $Mutation.workspace -Slug $Mutation.slug -Collection $Mutation.collection) 'dirty.json'
        if (Test-Path -LiteralPath $marker -PathType Leaf) { Remove-Item -LiteralPath $marker -Force }
        [pscustomobject]@{ status = 'cleared'; slug = $Mutation.slug; generation = 0; summary = 'unchanged (the mutation was rolled back)' }
    }
    catch {
        [pscustomobject]@{ status = 'dirty'; slug = $Mutation.slug; generation = 0; summary = "dirty until rebuilt: the marker could not be cleared: $($_.Exception.Message)" }
    }
}

function Complete-BookRenameMutation {
    <#
    .SYNOPSIS
        Close a mutation window across a change of Book identity: the old slug's store is retired and
        the new slug's first generation is committed. Never throws.

    .DESCRIPTION
        A rename is the one mutation that changes which Book the manifest is about, and rung 2
        recorded the consequence as a known limit: the old slug's store survives as an orphan
        describing a Book at a path that no longer exists. It is not a leak -- the contents were
        always catalog-class -- but it is a stale answer waiting to be found.

        The manifest is not moved, it is retired and regenerated. Generation N of the old slug
        describes a Book with the old slug and the old title inside it; carrying those files forward
        under a new name would make the store's history disagree with itself. A manifest is derived
        state, so the cheap and truthful move is to throw it away and generate the new identity's
        first generation from the Book as it now stands.

        THE ORDER IS CHOSEN SO EVERY CRASH POINT REFUSES. The new identity is marked dirty first, the
        old store is removed second, and the new generation is committed last. A crash after the first
        step leaves an old store that is dirty and a new store that is dirty -- both refuse. A crash
        after the second leaves only the new store, dirty, refusing. At no point does a store answer
        for a Book that has moved.

        A CHANGE OF SHELF IS THE SAME MOVE. Archiving a Shelf Book changes its identity exactly as a
        rename does -- `shelf/<slug>` becomes `shelf/_archive/<slug>`, and its manifest must follow it
        into the `shelf-archive` store or the Book drops out of Discovery, which is what archiving
        used to do. So -NewCollection generalises this from "new slug" to "new identity", and the
        ordering argument above is unchanged: it never depended on WHICH field moved.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)][object]$Mutation,
        [Parameter(Mandatory = $true)][string]$NewSlug,
        [string]$NewBookRoot = '',
        [Parameter(Mandatory = $true)][object]$NewLock,
        # Defaults to the mutation's own collection, which is what a rename wants.
        [string]$NewCollection = '',
        # Required whenever the new identity is not an active Shelf Book, for the reason
        # Invoke-BookManifestTransaction states: nothing here can read those pages.
        [object]$Manifest = $null
    )

    try {
        if ([string]::IsNullOrWhiteSpace($NewCollection)) { $NewCollection = $Mutation.collection }
        if ([string]::IsNullOrWhiteSpace($NewBookRoot)) { $NewBookRoot = New-BookRootFromManifestCollection $NewCollection $NewSlug }
        $renamed = Enter-BookMutation -Workspace $Mutation.workspace -Slug $NewSlug -BookRoot $NewBookRoot `
            -Reason $Mutation.reason -Lock $NewLock -Collection $NewCollection
        # -Collection, which this call did not pass before and did not need to while a rename was the
        # only caller: the parameter defaults to 'shelf', so a move out of any OTHER store would have
        # left the old manifest in place and deleted an unrelated Shelf Book's store if one shared the
        # slug. It is the mutation's own collection, never the new one.
        Remove-BookManifestStore -Workspace $Mutation.workspace -Slug $Mutation.slug -Collection $Mutation.collection | Out-Null
        $result = Complete-BookMutation -Mutation $renamed -Manifest $Manifest
        if ($result.status -ceq 'committed') {
            [pscustomobject]@{
                status     = 'committed'
                slug       = $NewSlug
                generation = $result.generation
                summary    = "generation $($result.generation) committed under $NewBookRoot; the store for $($Mutation.book_root) was retired"
            }
        }
        else { $result }
    }
    catch {
        [pscustomobject]@{
            status     = 'dirty'
            slug       = $NewSlug
            generation = 0
            summary    = "dirty until rebuilt: $($_.Exception.Message)"
        }
    }
}

# ---------------------------------------------------------------------------------------------------
# Self-test. Fixture-only and offline; run by Invoke-LibraryChecks.ps1 as
# `book-manifest-transaction.selftest`.
